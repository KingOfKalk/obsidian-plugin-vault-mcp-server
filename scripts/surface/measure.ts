/**
 * Measures the agent-facing surface of the MCP server (#450): the
 * `instructions` string, `tools/list` and `prompts/list`, as a real SDK
 * client receives them.
 *
 * Two views of `tools/list` are counted:
 *  - **full**: the whole `tools/list` result as compact JSON;
 *  - **model view**: only `name`, `description` and `input_schema` per tool,
 *    the Anthropic Messages API tool shape. This assumes the client passes
 *    nothing else to the model; clients may differ.
 *
 * Sizes are characters of compact JSON (`JSON.stringify` without spaces).
 * Tokens are estimated as chars / 4 and never stored.
 *
 * This file only computes sizes; `collect.ts` connects the server. It does
 * not import `src/`, so `scripts/ci-summary.ts` can parse results cheaply.
 * Dev-only: nothing under `src/` imports this, so it never reaches main.js.
 */

/** Raw responses as the client received them. */
export interface SurfaceSnapshot {
  instructions: string;
  tools: Record<string, unknown>[];
  prompts: Record<string, unknown>[];
}

/** Sizes in characters, per part of the surface. */
export interface SurfaceTotals {
  /** Server `instructions` (sent once per session). */
  instructions: number;
  /** `tools/list` result as compact JSON. */
  toolsList: number;
  /** name + description + input_schema of every tool. */
  modelView: number;
  /** Sum of the tool `description` strings. */
  toolDescriptions: number;
  /** Sum of the `inputSchema` objects as compact JSON. */
  inputSchemas: number;
  /** Sum of all `description` strings inside the input schemas. */
  inputSchemaDescriptions: number;
  /** Sum of the `outputSchema` objects as compact JSON. */
  outputSchemas: number;
  /** `prompts/list` result as compact JSON. */
  promptsList: number;
}

/** Sizes of one tool or one module, in characters. */
export interface SurfaceSizes {
  toolsList: number;
  modelView: number;
}

export interface ModuleSurface extends SurfaceSizes {
  tools: number;
}

export interface ToolSurface extends SurfaceSizes {
  module: string;
}

/** One measured tool set (every module, or the default-enabled ones). */
export interface SurfaceView {
  toolCount: number;
  totals: SurfaceTotals;
}

export interface SurfaceMeasurement {
  /** Every module and tool enabled, extras included. */
  all: SurfaceView & {
    modules: Record<string, ModuleSurface>;
    tools: Record<string, ToolSurface>;
  };
  /** Module and tool states of a fresh install (editor, workspace, ui and extras off; empty command allowlist). */
  defaults: SurfaceView;
}

/** The baseline file adds a comment for readers of the JSON. */
export interface SurfaceBaselineFile extends SurfaceMeasurement {
  $comment: string;
}

export const BASELINE_COMMENT =
  'Agent-facing surface sizes in characters of compact JSON (#450). Generated by `npm run surface:update`; checked by tests/scripts/surface-budget.test.ts. ~tokens = chars / 4.';

/** Characters of `value` as compact JSON. */
export function jsonChars(value: unknown): number {
  return JSON.stringify(value).length;
}

/** Estimated tokens for a character count. */
export function approxTokens(chars: number): number {
  return Math.round(chars / 4);
}

/** Sum of the lengths of every string under a `description` key. */
export function descriptionChars(value: unknown): number {
  if (Array.isArray(value)) return value.reduce<number>((n, v) => n + descriptionChars(v), 0);
  if (typeof value !== 'object' || value === null) return 0;
  let n = 0;
  for (const [key, v] of Object.entries(value)) {
    n += key === 'description' && typeof v === 'string' ? v.length : descriptionChars(v);
  }
  return n;
}

/** What a Messages-API style client hands the model for one tool. */
export function modelViewOf(tool: Record<string, unknown>): Record<string, unknown> {
  return {
    name: tool.name,
    description: tool.description ?? '',
    input_schema: tool.inputSchema,
  };
}

function toolName(tool: Record<string, unknown>): string {
  return typeof tool.name === 'string' ? tool.name : '';
}

export function totalsOf(snapshot: SurfaceSnapshot): SurfaceTotals {
  const { tools } = snapshot;
  const sum = (f: (t: Record<string, unknown>) => number): number =>
    tools.reduce((n, t) => n + f(t), 0);
  return {
    instructions: snapshot.instructions.length,
    toolsList: jsonChars({ tools }),
    modelView: jsonChars(tools.map(modelViewOf)),
    toolDescriptions: sum((t) => (typeof t.description === 'string' ? t.description.length : 0)),
    inputSchemas: sum((t) => (t.inputSchema === undefined ? 0 : jsonChars(t.inputSchema))),
    inputSchemaDescriptions: sum((t) => descriptionChars(t.inputSchema)),
    outputSchemas: sum((t) => (t.outputSchema === undefined ? 0 : jsonChars(t.outputSchema))),
    promptsList: jsonChars({ prompts: snapshot.prompts }),
  };
}

/**
 * Measure a snapshot. `moduleOf` maps a tool name to its module id; tools
 * it does not know are grouped under `unknown`.
 */
export function measureSnapshot(
  snapshot: SurfaceSnapshot,
  moduleOf: ReadonlyMap<string, string>,
): SurfaceMeasurement['all'] {
  const tools: Record<string, ToolSurface> = {};
  const modules: Record<string, ModuleSurface> = {};
  for (const tool of snapshot.tools) {
    const name = toolName(tool);
    const module = moduleOf.get(name) ?? 'unknown';
    const sizes = { toolsList: jsonChars(tool), modelView: jsonChars(modelViewOf(tool)) };
    tools[name] = { module, ...sizes };
    const m = (modules[module] ??= { tools: 0, toolsList: 0, modelView: 0 });
    m.tools += 1;
    m.toolsList += sizes.toolsList;
    m.modelView += sizes.modelView;
  }
  return { toolCount: snapshot.tools.length, totals: totalsOf(snapshot), modules, tools };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isNumberRecord(value: unknown, keys: readonly string[]): boolean {
  return isRecord(value) && keys.every((k) => typeof value[k] === 'number');
}

const TOTAL_KEYS: readonly (keyof SurfaceTotals)[] = [
  'instructions',
  'toolsList',
  'modelView',
  'toolDescriptions',
  'inputSchemas',
  'inputSchemaDescriptions',
  'outputSchemas',
  'promptsList',
];

function isView(value: unknown): value is SurfaceView {
  return (
    isRecord(value) &&
    typeof value.toolCount === 'number' &&
    isNumberRecord(value.totals, TOTAL_KEYS)
  );
}

/** Parse a measurement or baseline file. Returns null when it is not one. */
export function parseSurface(json: string): SurfaceMeasurement | null {
  let data: unknown;
  try {
    data = JSON.parse(json);
  } catch {
    return null;
  }
  if (!isRecord(data) || !isView(data.all) || !isView(data.defaults)) return null;
  const all = data.all as unknown as Record<string, unknown>;
  if (!isRecord(all.tools) || !isRecord(all.modules)) return null;
  for (const tool of Object.values(all.tools)) {
    if (!isRecord(tool) || !isNumberRecord(tool, ['toolsList', 'modelView'])) return null;
    if (typeof tool.module !== 'string') return null;
  }
  for (const m of Object.values(all.modules)) {
    if (!isNumberRecord(m, ['tools', 'toolsList', 'modelView'])) return null;
  }
  return data as unknown as SurfaceMeasurement;
}

/** Serialise a measurement as the committed baseline file. */
export function toBaselineJson(measurement: SurfaceMeasurement): string {
  const file: SurfaceBaselineFile = { $comment: BASELINE_COMMENT, ...measurement };
  return `${JSON.stringify(file, null, 2)}\n`;
}
