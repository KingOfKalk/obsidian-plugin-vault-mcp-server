/**
 * Composes the per-module pages and the index page that together form
 * `docs/tools.generated.md` + `docs/tools/<module>.generated.md`. Pure
 * string functions — file I/O lives in `scripts/list-tools.ts`.
 */

import { z } from 'zod';
import { inputShapeToTable, outputSchemaToTables } from './schema-to-table';

/**
 * One recorded successful call, rendered under the tool's section. The
 * response is the `structuredContent` when the tool returned one, otherwise
 * its `content` blocks.
 */
export interface ToolExampleDoc {
  arguments: Record<string, unknown>;
  response: { kind: 'structuredContent' | 'content'; value: unknown };
}

export interface ToolDoc {
  name: string;
  title: string;
  description: string;
  schema: z.ZodRawShape;
  outputSchema: z.ZodRawShape | z.ZodTypeAny | undefined;
  readOnly: boolean;
  destructive: boolean;
  example?: ToolExampleDoc;
}

export interface ModuleDoc {
  moduleId: string;
  moduleName: string;
  tools: ToolDoc[];
}

const BANNER =
  '<!-- AUTO-GENERATED by `npm run docs:tools`. Do not edit manually. -->';

function check(value: boolean): string {
  return value ? '✓' : '';
}

export function renderIndexPage(modules: ModuleDoc[]): string {
  const lines: string[] = [];
  lines.push(BANNER);
  lines.push('');
  lines.push('# Tool Registry Snapshot');
  lines.push('');
  lines.push(
    'This file is regenerated from the tool registry and committed so CI can detect doc drift.',
  );
  lines.push('');

  // Summary table — preserved verbatim from the previous renderer.
  lines.push('| Module ID | Module Name | Count | Tools |');
  lines.push('|---|---|---|---|');
  let total = 0;
  for (const m of modules) {
    total += m.tools.length;
    const names = m.tools.map((t) => t.name).join(', ');
    lines.push(
      `| \`${m.moduleId}\` | ${m.moduleName} | ${String(m.tools.length)} | ${names} |`,
    );
  }
  lines.push('');
  lines.push(`**Total tools:** ${String(total)} across ${String(modules.length)} modules.`);
  lines.push('');

  // Per-module annotation tables, each prefixed by the schema link.
  lines.push('## Tools by module');
  lines.push('');
  for (const m of modules) {
    lines.push(`### ${m.moduleName} (\`${m.moduleId}\`)`);
    lines.push('');
    lines.push(
      `Schemas → [docs/tools/${m.moduleId}.generated.md](tools/${m.moduleId}.generated.md)`,
    );
    lines.push('');
    lines.push('| Name | Title | readOnly | destructive |');
    lines.push('|---|---|---|---|');
    for (const t of m.tools) {
      lines.push(
        `| \`${t.name}\` | ${t.title} | ${check(t.readOnly)} | ${check(t.destructive)} |`,
      );
    }
    lines.push('');
  }

  return lines.join('\n').trimEnd() + '\n';
}

export function renderModulePage(module: ModuleDoc): string {
  const lines: string[] = [];
  lines.push(BANNER);
  lines.push('');
  lines.push(`# ${module.moduleName} (\`${module.moduleId}\`)`);
  lines.push('');
  lines.push(
    `Auto-generated schema reference for the \`${module.moduleId}\` module. See [../tools.generated.md](../tools.generated.md) for the full registry index.`,
  );
  lines.push('');

  for (const tool of module.tools) {
    lines.push(`### ${tool.name}`);
    lines.push('');
    lines.push(`**${tool.title}**`);
    lines.push('');
    lines.push(tool.description.trim());
    lines.push('');
    lines.push('#### Input');
    lines.push('');
    lines.push(inputShapeToTable(tool.schema));
    lines.push('');
    lines.push('#### Output');
    lines.push('');
    lines.push(outputSchemaToTables(tool.outputSchema));
    lines.push('');
    if (tool.example) {
      lines.push(...renderExample(tool.name, tool.example));
    }
  }

  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

/** Strings longer than this are cut in rendered examples. */
export const EXAMPLE_MAX_STRING = 300;
/** Arrays longer than this are cut in rendered examples. */
export const EXAMPLE_MAX_ITEMS = 10;

/**
 * Shorten long strings and arrays so example blocks stay readable. Cuts are
 * marked inline: a string ends with `… [truncated, N more chars]` and an
 * array gets a final `"… N more items"` element.
 */
export function truncateExampleValue(value: unknown): unknown {
  if (typeof value === 'string') {
    if (value.length <= EXAMPLE_MAX_STRING) return value;
    const rest = value.length - EXAMPLE_MAX_STRING;
    return `${value.slice(0, EXAMPLE_MAX_STRING)}… [truncated, ${String(rest)} more chars]`;
  }
  if (Array.isArray(value)) {
    const kept = value.slice(0, EXAMPLE_MAX_ITEMS).map(truncateExampleValue);
    if (value.length > EXAMPLE_MAX_ITEMS) {
      kept.push(`… ${String(value.length - EXAMPLE_MAX_ITEMS)} more items`);
    }
    return kept;
  }
  if (value !== null && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      out[k] = truncateExampleValue(v);
    }
    return out;
  }
  return value;
}

/** A fenced block whose fence is longer than any backtick run inside it. */
function fenced(lang: string, body: string): string[] {
  const longestRun = Math.max(0, ...(body.match(/`+/g) ?? []).map((r) => r.length));
  const fence = '`'.repeat(Math.max(3, longestRun + 1));
  return [`${fence}${lang}`, body, fence];
}

function renderExample(name: string, example: ToolExampleDoc): string[] {
  const request = JSON.stringify(
    { name, arguments: truncateExampleValue(example.arguments) },
    null,
    2,
  );
  return [
    '#### Example',
    '',
    'Request (`tools/call` params):',
    '',
    ...fenced('json', request),
    '',
    ...renderResponse(example.response),
  ];
}

/**
 * The response of an example. `structuredContent` is shown as JSON (the
 * text block carries the same JSON). Content blocks of document and binary
 * tools (#467) are shown one by one: a text block as the text the model
 * reads, any other block as JSON.
 */
function renderResponse(response: ToolExampleDoc['response']): string[] {
  if (response.kind === 'structuredContent' || !Array.isArray(response.value)) {
    const json = JSON.stringify(truncateExampleValue(response.value), null, 2);
    return [`Response (\`${response.kind}\`):`, '', ...fenced('json', json), ''];
  }
  const lines: string[] = ['Response (`content`):', ''];
  for (const block of response.value as Array<{ type?: unknown; text?: unknown }>) {
    if (block.type === 'text' && typeof block.text === 'string') {
      lines.push('Text block:', '', ...fenced('text', block.text), '');
    } else {
      const json = JSON.stringify(truncateExampleValue(block), null, 2);
      lines.push(`\`${String(block.type)}\` block:`, '', ...fenced('json', json), '');
    }
  }
  return lines;
}
